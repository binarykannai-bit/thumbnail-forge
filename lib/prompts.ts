これらの成功サムネから以下の要素をすべて抽出し、生成する3つのサムネプロンプトに**何らかの形で反映**してください：

1. **構図・レイアウト**
   - 主要素（人物・文字・図解）の配置パターン
   - 余白の使い方、画面分割の比率
   - 視線誘導の流れ（どこから見て、どこに導かれるか）

2. **色彩戦略**
   - メインカラー・アクセントカラーの組合せ
   - 背景と前景のコントラスト強度
   - 強調色の面積比

3. **文字・タイポグラフィ**
   - フォントの太さ・種類（極太ゴシック等）
   - 縁取り・影・グラデーションの付け方
   - 文字サイズと画面占有率
   - 行間・字間の設計

4. **表情・ポーズ（人物がいる場合）**
   - 感情表現の強度（驚き・困惑・喜びなど）
   - 視線の向き、ポーズの角度
   - 顔の画面占有率

5. **演出要素**
   - 矢印・吹き出し・記号などの装飾パターン
   - エフェクト（光・煙・閃光など）
   - 区切り線・枠の使い方

6. **全体トーン**
   - 緊張感・カジュアルさのバランス
   - 明度・彩度の傾向
   - ジャンル感（ビジネス系・エンタメ系など）

