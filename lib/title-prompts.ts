/**
 * タイトル用の数字ホワイトリストセクション。
 */
function buildNumbersSectionForTitle(extracted: ExtractedNumbers): string {
  if (!extracted || extracted.all.length === 0) {
    return `# 🔢 数字の使用制約

**原稿から数字が抽出できませんでした。タイトルに具体的な数字を一切使用しないでください。**`;
  }

  return `# 🔢 タイトルで使用可能な数字（ホワイトリスト）

**原稿から抽出された下記の数字のみ**をタイトル内で使用してください:

${extracted.all.map((n) => `「${n}」`).join('、')}

**リスト外の数字を1つでも使うのは絶対NG**。リストに無い金額・人数・割合・期間などを勝手に作り出してはいけません。
**数字を組み合わせて新しい数字を作るのもNG**（例: 「150万」「160万」→ 「10万円差」を作るのはNG）`;
}
